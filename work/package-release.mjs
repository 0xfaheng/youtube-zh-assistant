import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
const run=promisify(execFile), out=path.resolve(import.meta.dirname,'../outputs'), root=path.join(out,'youtube-zh-assistant'), source=path.join(root,'extension'), target=path.join(out,'Chrome插件-YouTube中文字幕');
const version=JSON.parse(await fs.readFile(path.join(root,'package.json'),'utf8')).version;
const developmentRecord=path.join(root,'开发记录',`v${version}.md`);
let developmentText;
try {developmentText=await fs.readFile(developmentRecord,'utf8');}
catch {throw new Error(`版本 ${version} 缺少开发记录：${developmentRecord}`);}
assert.ok(developmentText.includes(version)&&developmentText.length>=400,'开发记录必须写明版本与具体开发内容');
for(const heading of ['## 版本信息','## 改动内容','## 验证结果','## 交付文件','## 回退方式'])assert.ok(developmentText.includes(heading),`开发记录缺少 ${heading}`);
assert.ok(!/待验证|待补充|尚未完成/.test(developmentText),'开发记录存在未完成事项，不能打包交付');
assert.equal(JSON.parse(await fs.readFile(path.join(source,'manifest.json'),'utf8')).version,version,'插件和安装元数据版本不一致');
const popupJS=await fs.readFile(path.join(source,'popup.js'),'utf8'),popupHTML=await fs.readFile(path.join(source,'popup.html'),'utf8');
assert.ok(popupJS.includes("$('version').textContent=chrome.runtime.getManifest().version"),'插件面板必须读取实际扩展版本');
assert.match(popupHTML,/<span id="version" class="version"><\/span>/,'插件面板不能写死版本号');
const serviceText=await fs.readFile(path.join(root,'server/app.mjs'),'utf8');
assert.ok([...serviceText.matchAll(/version:\s*'([^']+)'/g)].length>=2,'服务版本标识缺失');
assert.ok([...serviceText.matchAll(/version:\s*'([^']+)'/g)].every(m=>m[1]===version),'服务和插件版本不一致');
const rar=path.join(out,`Chrome插件-YouTube中文字幕-v${version}.rar`), zip=path.join(out,`youtube-zh-assistant-v${version}.zip`), rarExe='C:/Program Files/WinRAR/Rar.exe';
const files=(await fs.readdir(source,{withFileTypes:true})).filter(p=>p.isFile()).map(p=>p.name).sort();
await fs.mkdir(target,{recursive:true});
for(const name of files)await fs.copyFile(path.join(source,name),path.join(target,name));
assert.equal(JSON.parse(await fs.readFile(path.join(target,'manifest.json'),'utf8')).version,version);
const hash=async p=>createHash('sha256').update(await fs.readFile(p)).digest('hex');
for(const name of files)assert.equal(await hash(path.join(source,name)),await hash(path.join(target,name)));
await run(rarExe,['a','-r','-ep1','-idq',rar,target],{windowsHide:true,maxBuffer:1024*1024});
await run(rarExe,['t','-idq',rar],{windowsHide:true});
const check=path.join(import.meta.dirname,`rar-verify-${version}-${Date.now()}`);await fs.mkdir(check,{recursive:true});
await run(rarExe,['x','-idq',rar,check+path.sep],{windowsHide:true});
const extracted=path.join(check,path.basename(target));assert.deepEqual((await fs.readdir(extracted)).sort(),files);
for(const name of files)assert.equal(await hash(path.join(source,name)),await hash(path.join(extracted,name)));
const report={date:new Date().toISOString(),version,developmentRecord,developmentRecordVerified:true,extensionFiles:files.length,loadedFolder:target,folderHashesMatch:true,rarFile:rar,rarExtractedHashesMatch:true,zipFile:zip,zipVerified:false};
const record=path.join(root,'verification/package-report.json');await fs.writeFile(record,JSON.stringify(report,null,2));
const args=['package-release.py','create',root,zip];
const first=await run('python',args,{cwd:import.meta.dirname,windowsHide:true});Object.assign(report,JSON.parse(first.stdout));
await fs.writeFile(record,JSON.stringify(report,null,2));
await run('python',args,{cwd:import.meta.dirname,windowsHide:true});
console.log(JSON.stringify({...report,rarBytes:(await fs.stat(rar)).size,zipBytes:(await fs.stat(zip)).size},null,2));
